"""Import libraries and configure the model"""

import torch
import numpy as np

from torch.utils.data import Dataset, DataLoader
from torch.optim import AdamW
from transformers import (
    AutoTokenizer,
    AutoModelForSequenceClassification
)

MODEL_NAME = "distilbert/distilroberta-base"
NUM_LABELS = 41

DEVICE = torch.device(
    "cuda" if torch.cuda.is_available() else "cpu"
)

print("Using device:", DEVICE)

"""Initialize DistilRoBERTa"""

def initialize_model(
    model_name=MODEL_NAME,
    num_labels=NUM_LABELS
):
    tokenizer = AutoTokenizer.from_pretrained(
        model_name
    )

    model = AutoModelForSequenceClassification.from_pretrained(
        model_name,
        num_labels=num_labels,
        problem_type="multi_label_classification"
    )

    model = model.to(DEVICE)

    return model, tokenizer


model, tokenizer = initialize_model()

print("Model initialized successfully!")
print("Number of labels:", model.config.num_labels)

"""Create the dataset class"""

class ContractDataset(Dataset):

    def __init__(self, texts, labels, tokenizer, max_length=256):
        assert len(texts) == len(labels)

        labels = np.asarray(labels, dtype=np.float32)

        assert labels.ndim == 2
        assert labels.shape[1] == NUM_LABELS

        self.encodings = tokenizer(
            texts,
            truncation=True,
            padding="max_length",
            max_length=max_length
        )

        self.labels = torch.tensor(
            labels,
            dtype=torch.float32
        )

    def __len__(self):
        return len(self.labels)

    def __getitem__(self, idx):

        item = {
            key: torch.tensor(values[idx])
            for key, values in self.encodings.items()
        }

        item["labels"] = self.labels[idx]

        return item

"""Create reusable training function"""

def train_model(
    model,
    train_loader,
    epochs=3,
    learning_rate=2e-5
):
    optimizer = AdamW(
        model.parameters(),
        lr=learning_rate
    )

    for epoch in range(epochs):

        model.train()
        total_loss = 0

        for batch in train_loader:

            batch = {
                key: value.to(DEVICE)
                for key, value in batch.items()
            }

            optimizer.zero_grad()

            outputs = model(**batch)

            loss = outputs.loss

            loss.backward()

            optimizer.step()

            total_loss += loss.item()

        avg_loss = total_loss / len(train_loader)

        print(
            f"Epoch {epoch + 1}/{epochs} "
            f"- Loss: {avg_loss:.4f}"
        )

    return model

"""Create reusable prediction function"""

def predict_clauses(
    text,
    model,
    tokenizer,
    threshold=0.5
):
    model.eval()

    inputs = tokenizer(
        text,
        return_tensors="pt",
        truncation=True,
        padding=True,
        max_length=256
    ).to(DEVICE)

    with torch.no_grad():
        outputs = model(**inputs)

        probabilities = torch.sigmoid(
            outputs.logits
        )

    predictions = (
        probabilities >= threshold
    ).int()

    return {
        "probabilities": probabilities.cpu().numpy()[0],
        "predictions": predictions.cpu().numpy()[0]
    }

"""Create example training data"""

texts = [
    "Either party may terminate this agreement with 30 days notice.",
    "The parties agree to maintain confidentiality."
]

labels = np.zeros((2, NUM_LABELS), dtype=np.float32)

# Placeholder label indices for testing
labels[0, 0] = 1
labels[1, 1] = 1

dataset = ContractDataset(
    texts,
    labels,
    tokenizer
)

train_loader = DataLoader(
    dataset,
    batch_size=2,
    shuffle=True
)

print("Number of training examples:", len(dataset))

"""Train the model"""



model = train_model(
    model,
    train_loader,
    epochs=1,
    learning_rate=2e-5
)

print("Training completed!")

"""Test predictions"""



sample_contract = """
This agreement may be terminated by either party
upon thirty days written notice.
"""

result = predict_clauses(
    sample_contract,
    model,
    tokenizer
)

print("Number of outputs:", len(result["probabilities"]))

print("\nPredicted label indices:")
print(np.where(result["predictions"] == 1)[0])

print("\nFirst 10 probabilities:")
print(result["probabilities"][:10])

"""Save the model"""

SAVE_PATH = "./cuad_distilroberta"

model.save_pretrained(SAVE_PATH)
tokenizer.save_pretrained(SAVE_PATH)

print("Model saved successfully!")

